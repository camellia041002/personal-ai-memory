import { copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const core = await readFile(path.join(root, "src", "core.js"), "utf8");
const worker = await readFile(path.join(root, "src", "worker.js"), "utf8");
const bundledCore = core.replace(/^export\s+/gmu, "");
const bundledWorker = worker.replace(/^import\s*\{[\s\S]*?\}\s*from\s*"\.\/core\.js";\s*/u, "");
const output = [
  "// Generated from ../src by npm run build:v8-package. Do not edit this file directly.",
  bundledCore.trim(),
  bundledWorker.trim(),
  "",
].join("\n\n");

await mkdir(path.join(root, "v8"), { recursive: true });
await writeFile(path.join(root, "v8", "worker.js"), output, "utf8");
await mkdir(path.join(root, "v8", "migrations"), { recursive: true });
for (const file of await readdir(path.join(root, "migrations"))) {
  if (file.endsWith(".sql")) {
    await copyFile(path.join(root, "migrations", file), path.join(root, "v8", "migrations", file));
  }
}
console.log("v8/worker.js generated from public src");
